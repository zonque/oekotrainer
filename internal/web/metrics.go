package web

import (
	"fmt"
	"io"
	"slices"
	"strconv"
	"strings"

	"kinobox/internal/monitor"
)

type metricWriter struct {
	w io.Writer
}

func (m metricWriter) header(name, typ, help string) {
	fmt.Fprintf(m.w, "# HELP %s %s\n# TYPE %s %s\n", name, help, name, typ)
}

func (m metricWriter) sample(name, labels string, v float64) {
	if labels != "" {
		name += "{" + labels + "}"
	}
	fmt.Fprintf(m.w, "%s %s\n", name, strconv.FormatFloat(v, 'g', -1, 64))
}

func (m metricWriter) single(name, typ, help string, v float64) {
	m.header(name, typ, help)
	m.sample(name, "", v)
}

// writeMetrics renders a snapshot in the Prometheus text exposition format.
func writeMetrics(w io.Writer, s monitor.Snapshot) {
	m := metricWriter{w}

	up := 0.0
	if s.Online {
		up = 1
	}
	m.single("kinobox_up", "gauge", "Whether readings are being received from the source.", up)
	m.header("kinobox_info", "gauge", "Name of the data source.")
	m.sample("kinobox_info", `source="`+escapeLabel(s.Source)+`"`, 1)

	if r := s.Reading; r != nil {
		m.single("kinobox_battery_voltage_volts", "gauge", "Battery voltage.", r.Voltage)
		m.single("kinobox_load_current_amperes", "gauge", "Current drawn by the consumers.", r.LoadCurrent)
		m.single("kinobox_load_power_watts", "gauge", "Power drawn by the consumers.", r.LoadPower)
		m.single("kinobox_generated_power_watts", "gauge", "Total power generated by all riders.", r.GeneratedPower)
		m.single("kinobox_temperature_celsius", "gauge", "KinoBox temperature.", r.Temperature)

		m.header("kinobox_rider_current_amperes", "gauge", "Generator current per rider.")
		for _, rd := range r.Riders {
			m.sample("kinobox_rider_current_amperes", riderLabel(rd.Position), rd.Current)
		}
		m.header("kinobox_rider_power_watts", "gauge", "Generated power per rider.")
		for _, rd := range r.Riders {
			m.sample("kinobox_rider_power_watts", riderLabel(rd.Position), rd.Power)
		}

		m.header("kinobox_protection_state", "gauge", "Protection state: 0 = ok, 1 = warning, 2 = tripped.")
		st := r.Status
		for _, p := range []struct {
			name string
			v    uint8
		}{
			{"low_voltage", uint8(st.LowVoltage)},
			{"high_voltage", uint8(st.HighVoltage)},
			{"high_temperature", uint8(st.HighTemperature)},
			{"high_current", uint8(st.HighCurrent)},
		} {
			m.sample("kinobox_protection_state", `protection="`+p.name+`"`, float64(p.v))
		}
		m.single("kinobox_protection_countdown_seconds", "gauge", "Seconds until a tripped protection is reset.", float64(st.Countdown))
	}

	m.header("kinobox_rider_energy_joules_total", "counter", "Energy generated per rider since start.")
	for i, e := range s.RiderEnergyJ {
		m.sample("kinobox_rider_energy_joules_total", riderLabel(i+1), e)
	}
	m.single("kinobox_generated_energy_joules_total", "counter", "Energy generated by all riders since start.", s.GeneratedEnergyJ)
	m.single("kinobox_consumed_energy_joules_total", "counter", "Energy consumed since start.", s.ConsumedEnergyJ)
	m.single("kinobox_readings_total", "counter", "Readings received from the source.", float64(s.Readings))
	m.single("kinobox_backend_restarts_total", "counter", "Times the backend was restarted after a failure.", float64(s.Restarts))
	keys := make([]string, 0, len(s.BackendCounters))
	for k := range s.BackendCounters {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	for _, k := range keys {
		m.single("kinobox_backend_"+k+"_total", "counter", "Backend-specific counter "+k+".", float64(s.BackendCounters[k]))
	}
	if !s.LastReading.IsZero() {
		m.single("kinobox_last_reading_timestamp_seconds", "gauge", "Unix time of the last reading.",
			float64(s.LastReading.UnixNano())/1e9)
	}
}

func riderLabel(pos int) string { return `rider="` + strconv.Itoa(pos) + `"` }

var labelEscaper = strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`)

func escapeLabel(s string) string { return labelEscaper.Replace(s) }
